-- 20261010 — إصلاح تصنيف الباقات المشتركة
--
-- كان نموذج الباقات القديم يقبل «مكة» و«مكة والمدينة» لكن بعض السجلات
-- سُميت بوضوح «مكة والمدينة» مع بقاء destination = «مكة». عند المستفيد
-- تصبح بطاقة المدينة ظاهرةً في شاشة مكة. نصحح الحالات غير الملتبسة فقط؛
-- لا نخمّن من اسم باقةٍ لا يذكر الوجهتين معاً.

update public.packages
   set destination = 'مكة والمدينة'
 where destination is distinct from 'مكة والمدينة'
   and regexp_replace(coalesce(name, ''), '[[:space:]]+', ' ', 'g') like '%مكة والمدينة%';

comment on column public.packages.destination is
  'وجهة الباقة التجارية: مكة أو مكة والمدينة. مدينة الانطلاق تحفظ على الرحلة ومحطاتها لا هنا.';
