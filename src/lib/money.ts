/* المبلغ نصّاً — صياغةٌ واحدة لكل ريال في التطبيق.

   ما رآه الفريق: «المبلغ يظهر أحياناً رقماً ثم ريال سعودي وأحياناً ر.س».
   وما كان تحته: ثلاثة تعريفات لدالّة money — واحدة في lib/utils لا
   يستوردها أحد (ميتة)، وثانية في customer/ui/tokens بلا وحدة، وثالثة
   محليّة في شاشة الرئيسية — و«ر.س» ملصوقةٌ يدوياً في أربعة وثلاثين موضعاً
   بصيغة `n.toLocaleString("en-US") + " ر.س"`، وموضعٌ واحد يكتب «ريال سعودي».

   القاعدة هنا: الوحدة ثابتٌ واحد، والأرقام لاتينية بفواصل آلاف كما هي
   اليوم في كل الشاشات (toLocaleString("en-US")) — تغييرها إلى الأرقام
   العربية-الهندية قرارٌ آخر لا يُتخذ ضمناً في دالّة تنسيق.

   والتقريب صريح: المبالغ في النظام أعدادٌ صحيحة (سعر الليلة × السعة ×
   الليالي)، وكسرٌ عشري يظهر في الواجهة معناه خطأ حسابٍ لا مبلغ حقيقي —
   فيُقرَّب ولا يُعرض ".0000000001". */

/** وحدة العملة — الصيغة القصيرة المعتمدة في اللوحة وفي واجهة المستفيد. */
export const SAR = "ر.س";

/** الرقم وحده بفواصل الآلاف، بلا وحدة.
    لبطاقةٍ تكتب الوحدة سطراً مستقلاً تحت الرقم. */
export function sarNumber(n: number): string {
  return Math.round(Number(n) || 0).toLocaleString("en-US");
}

/** المبلغ كاملاً: «1,250 ر.س». هذه هي الصيغة الافتراضية في كل موضع. */
export function sar(n: number): string {
  return `${sarNumber(n)} ${SAR}`;
}

/** مبلغٌ لكل وحدة: «280 ر.س / ليلة». الوحدة تُمرَّر بلا شرطة مائلة. */
export function sarPer(n: number, unit: string): string {
  return `${sar(n)} / ${unit}`;
}

/** مبلغٌ في رسالة واتساب أو نصٍّ مُرسَل — نفس الصياغة، صريحةً أنها للنصّ
    لا للواجهة، كي لا تتفرّق الصيغتان يوماً. */
export const sarText = sar;
