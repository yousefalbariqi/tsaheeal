/* اسم الفندق — كلمة «فندق» تُكتب مرّةً واحدة.

   ما رآه الفريق: «فندق فندق ايلاف قنوان». وسببه أن الاسم المخزَّن يبدأ
   بـ«فندق» وبطاقة الإدارة تكتب `فندق {hotel.name}` — فكلمةٌ من البيانات
   وكلمةٌ من الشفرة تجتمعان في السطر نفسه.

   القاعدة: **البادئة ليست جزءاً من الاسم.** المخزَّن هو الاسم المجرَّد
   («دار الإيمان جراند»)، والعرض يضيف «فندق» حيث تناسبه الجملة. هذا يمنع
   التكرار من جهتين معاً: عند الحفظ (تُنزع البادئة من مدخل الموظف) وعند
   العرض (تُنزع قبل الإضافة، فالصفوف القديمة تظهر صحيحةً قبل أي تنظيف).

   والتنظيف متكرّر لا مرّة واحدة: «فندق فندق ايلاف» يحتاج نزع بادئتين،
   ونزعُ واحدةٍ يترك المشكلة قائمةً بنصفها. */

/* البادئات المنزوعة. «فندق» و«فُندق» بالتشكيل، ومعهما «الفندق» —
   يكتبها بعض الموظفين معرَّفةً. الحدّ \s+ إلزامي: «فندقية» ليست بادئة. */
const PREFIX = /^\s*(?:ال)?ف[ُ]?ندق\s+/;

/** الاسم المجرَّد كما يجب أن يُخزَّن — بلا بادئة ولا مسافات زائدة. */
export function cleanHotelName(raw: string): string {
  let s = (raw || "").replace(/\s+/g, " ").trim();
  /* حدٌّ أعلى للتكرار حرصاً لا حاجةً: نصٌّ من مئة «فندق» لن يدور بلا نهاية. */
  for (let i = 0; i < 8 && PREFIX.test(s); i++) s = s.replace(PREFIX, "").trim();
  return s;
}

/** هل يحتاج مدخل الموظف تنظيفاً؟ — لتنبيهٍ لطيف تحت الحقل. */
export const hasHotelPrefix = (raw: string): boolean => PREFIX.test((raw || "").trim());

/** الاسم كما يُعرض: «فندق دار الإيمان جراند».

    يُستدعى في كل موضعٍ كان يكتب `فندق {name}` بيده — البطاقة، وصفحة
    الباقة، وشاشة المستفيد. الاسم الفارغ يعيد نصّاً فارغاً لا كلمة «فندق»
    وحدها معلَّقة. */
export function hotelDisplayName(raw: string): string {
  const clean = cleanHotelName(raw);
  return clean ? `فندق ${clean}` : "";
}
