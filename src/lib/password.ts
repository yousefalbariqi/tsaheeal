/* سياسة كلمة المرور — مصدر واحد للقاعدة ولنصّها.

   كانت الشاشة تقول «6 أحرف على الأقل» والتحقّق يقبل `pw.length < 6` —
   أي أن ستّة أصفار متتالية كلمةُ مرورٍ صالحة لحسابٍ يملك لوحة الإدارة
   كلّها. والفريق رصده: «طبّق سياسة أقوى».

   والحدّ الأدنى ١٢ لا ٨: طول العبارة يغلب تعقيدها في مقاومة التخمين،
   و«عبارة من ثلاث كلمات» أسهل حفظاً من «Aa1!xy» وأمنع منها بمراحل.
   لذلك لا نشترط رموزاً ولا خلط حالات — اشتراطها يدفع إلى «Password1!»
   وهي أضعف مما تبدو، ويدفع إلى كتابتها على ورقة.

   ما نشترطه ثلاثة فقط: طولٌ كافٍ، وألّا تكون من قائمة الشائع، وألّا
   تكون بريد المستخدم أو اسمه — وهي أوّل ما يجرّبه المهاجم.

   ملاحظة على الموجة ٥: هذا الملفّ سيبقى للحالات التي يضبط فيها
   المستخدم كلمته بنفسه بعد رابط الدعوة؛ أمّا حقل «كلمة المرور» الذي
   يكتبه المدير في نموذج الإضافة فيُحذف كلّه هناك. */

export const PASSWORD_MIN = 12;

/* أشيع ما يُجرَّب أولاً — مختصرة عمداً: قائمةٌ بعشرة آلاف كلمة تُشحن
   إلى المتصفّح ثمنُها أكبر من فائدتها، والحدّ الأدنى ١٢ يُسقط أكثرها
   أصلاً. المقارنة بلا حساسية لحالة الأحرف. */
const COMMON = [
  "password", "passw0rd", "123456789012", "qwertyuiop", "administrator",
  "letmein12345", "welcome12345", "iloveyou1234", "abcd1234abcd",
  "كلمةالمرور", "تساهيل123456",
];

export interface PasswordCheck {
  ok: boolean;
  /** رسالة عربية جاهزة للعرض، أو "" حين تصحّ. */
  error: string;
}

/** يفحص كلمة المرور مقابل السياسة.
    `identity` أجزاءُ هوية المستخدم (البريد، الاسم) التي لا يجوز أن
    تكون كلمةُ مروره واحدةً منها. */
export function checkPassword(pw: string, identity: (string | undefined)[] = []): PasswordCheck {
  const v = pw ?? "";
  if (!v) return { ok: false, error: "أدخل كلمة المرور" };
  if (v.length < PASSWORD_MIN) {
    return { ok: false, error: `كلمة المرور ${PASSWORD_MIN} محرفاً على الأقل — العبارة الطويلة أقوى من الرموز` };
  }
  /* مسافات الطرفين تُعدّ في الطول ثم تُفقد عند اللصق في حقل الدخول —
     فتصير كلمةٌ «صالحة» لا تفتح الحساب. */
  if (v !== v.trim()) return { ok: false, error: "لا تبدأ كلمة المرور بمسافة ولا تنتهي بها" };

  const low = v.toLowerCase();
  if (COMMON.some(c => low === c)) {
    return { ok: false, error: "كلمة مرور شائعة — اختر عبارة لا تُخمَّن" };
  }
  /* البريد كاملاً أو الجزء الذي قبل @؛ والاسم كاملاً. أوّل ثلاث
     محاولات لأي مهاجم يعرف البريد. */
  const parts = identity
    .flatMap(x => [x, x?.split("@")[0]])
    .map(x => (x ?? "").trim().toLowerCase())
    .filter(x => x.length >= 4);
  if (parts.some(x => low === x || low.includes(x))) {
    return { ok: false, error: "لا تجعل كلمة المرور اسمك أو بريدك" };
  }
  return { ok: true, error: "" };
}

/** نصّ إرشادي واحد — يظهر تحت الحقل ونائباً عنه في placeholder. */
export const PASSWORD_HINT =
  `${PASSWORD_MIN} محرفاً على الأقل — يُفضَّل عبارة من ثلاث كلمات`;
