/* مدن المملكة — قائمة مغلقة بدل كتابةٍ حرّة.

   العلّة التي رصدها الفريق: «الدمام» و«مدينة الدمام» تظهران مدينتين.
   والحقل نصٌّ حرّ، فكل موظفٍ يكتبها كما اعتاد — «جده» و«جدة»، و«مكة»
   و«مكة المكرمة»، و«الرياض » بمسافةٍ زائدة. والعدّاد يقول أربع مدن
   وهي واحدة، والتصفية بالمدينة تُخفي نصف الفروع عمّن اختار الصيغة
   الأخرى.

   ── لماذا قائمة لا تطبيعٌ عند الحفظ ──

   التطبيع يصلح ما كُتب، والقائمة تمنع أن يُكتب. والفرق أن التطبيع يحتاج
   قاعدةً لكل صيغةٍ لم تخطر ببال كاتبها — وأوّل صيغةٍ جديدة تفلت منه.
   القائمة تُغلق الباب: من أراد مدينةً غير مذكورة أضافها هنا مرّةً
   واحدة، فتصير متاحةً للجميع بالصيغة نفسها.

   والمرادفات أدناه ليست بديلاً عن القائمة بل جسرٌ إليها: بها يُطابَق
   المكتوبُ سابقاً في القاعدة على صيغته المعتمدة مرّةً واحدة في الترحيل،
   وبها يجد البحثُ «جده» حين يكتبها من يبحث. */

/** المدن المعتمدة — الصيغة المكتوبة هي المخزَّنة. */
export const SAUDI_CITIES = [
  "الرياض", "جدة", "مكة المكرمة", "المدينة المنورة", "الدمام", "الخبر", "الظهران",
  "الطائف", "تبوك", "بريدة", "عنيزة", "الأحساء", "الهفوف", "حائل", "أبها", "خميس مشيط",
  "نجران", "جازان", "ينبع", "الجبيل", "القطيف", "عرعر", "سكاكا", "الباحة", "بيشة",
  "الخرج", "الزلفي", "المجمعة", "شقراء", "الدوادمي", "وادي الدواسر", "رابغ", "القنفذة",
] as const;

export type SaudiCity = typeof SAUDI_CITIES[number];

/* المرادفات ← الصيغة المعتمدة. مكتوبةٌ بلا تشكيل ولا همزات متفاوتة،
   والمطابقة تمرّ على normalize أوّلاً فتكفي صيغةٌ واحدة لكل مرادف. */
const ALIASES: Record<string, string> = {
  "مدينه الدمام": "الدمام", "الدمام السعوديه": "الدمام",
  "جده": "جدة", "مدينه جده": "جدة",
  "مكه": "مكة المكرمة", "مكه المكرمه": "مكة المكرمة", "مكة": "مكة المكرمة", "ام القرى": "مكة المكرمة",
  "المدينه": "المدينة المنورة", "المدينه المنوره": "المدينة المنورة", "المدينة": "المدينة المنورة",
  "طيبه": "المدينة المنورة", "يثرب": "المدينة المنورة",
  "الرياض السعوديه": "الرياض", "مدينه الرياض": "الرياض",
  "الاحساء": "الأحساء", "الهفوف الاحساء": "الأحساء",
  "ابها": "أبها", "خميس": "خميس مشيط",
  "الخبر الشرقيه": "الخبر", "القصيم": "بريدة",
};

/** يوحّد شكل النصّ للمقارنة وحدها — لا يُخزَّن ناتجه.
    يزيل التشكيل والتطويل، ويوحّد الألف والهمزة والتاء المربوطة والياء. */
export function normalizeCity(raw: string): string {
  return (raw || "")
    .replace(/[ً-ْـ]/g, "")     // تشكيل وتطويل
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .trim();
}

/** يردّ المكتوب إلى صيغته المعتمدة، أو null إن لم يُعرف.

    null معناها «لا أعرفها» لا «خطأ»: الواجهة تعرضها كما هي وتطلب
    الاختيار من القائمة، ولا تدهس ما كتبه الموظف بتخمينٍ منها. */
export function canonicalCity(raw: string): string | null {
  const n = normalizeCity(raw);
  if (!n) return null;
  const direct = SAUDI_CITIES.find(c => normalizeCity(c) === n);
  if (direct) return direct;
  const alias = ALIASES[n];
  if (alias) return alias;
  return null;
}

/** خيارات القائمة، مع إبقاء قيمةٍ قديمة غير معروفة ظاهرةً بدل محوها.
    حذفُ القيمة الحالية من الخيارات يجعل الحقل يبدو فارغاً، فيحفظ الموظف
    الفرع وقد فقد مدينته بلا أن يمسّها. */
export function cityOptions(current?: string): { value: string; label: string }[] {
  const base: { value: string; label: string }[] = SAUDI_CITIES.map(c => ({ value: c as string, label: c as string }));
  const v = (current || "").trim();
  if (v && !SAUDI_CITIES.some(c => c === v)) {
    const fix = canonicalCity(v);
    base.unshift({ value: v, label: fix ? `${v} — تُحفظ ${fix}` : `${v} (غير معتمدة)` });
  }
  return base;
}
